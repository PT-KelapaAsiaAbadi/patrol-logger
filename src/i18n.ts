export type Lang = "id" | "en";
const dict: Record<Lang, Record<Key, string>> = { id, en };

export function translate(
	lang: Lang,
	key: Key,
	vars?: Record<string, string | number>,
): string {
	let s = dict[lang][key];
	if (vars)
		for (const [k, v] of Object.entries(vars))
			s = s.replace(`{${k}}`, String(v));
	return s;
}
